"""The SPI-NAND layout: partitions, UBI volumes and the BMT write policy.

This is the one definition. The loader and Linux device trees carry a region
generated from it, the BMT layer compiles a header generated from it, and the
image build and installer size their volumes from it.

    platform/partitions.py            # check the device trees are current
    platform/partitions.py --write    # regenerate their partition regions

Offsets are vendor-logical: stock U-Boot, our loader and Linux all translate
them through the vendor BBT shift and BMT substitution exactly once, so a
partition lands on the same physical blocks whichever stage addresses it.

Units carry one of two 512 MiB SPI-NAND parts. The byte layout is the same on
both; block, page and OOB sizes, and everything sized in blocks, follow the part
the images are built for: W1700K_NAND when set, else the part the last images
were built for (platform/build/images/nand-part), else the w25n04kv.
"""
import argparse
from collections import namedtuple
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
CHIP_BYTES = 0x20000000

# page/oob: bytes per page and OOB area; oob_free: the ECC-protected free OOB
# bytes (AUTO layout, 14 per 16-byte spare section); journal: the BMT
# transaction journal's physical block, the first reserve block after the BBT
# when the top of the chip has no factory-bad block (stock's pool is
# total * 8 / 100 good blocks, clamped to 250).
Part = namedtuple('Part', 'name page oob oob_free block_pages journal')
PARTS = {
    'w25n04kv': Part('w25n04kv', 0x800, 128, 56, 64, 4096 - 250 + 1),
    'w25n04l': Part('w25n04l', 0x1000, 256, 112, 64, 2048 - 2048 * 8 // 100 + 1),
}
BUILT_PART = ROOT / 'platform/build/images/nand-part'   # written by platform/images.py
_name = os.environ.get('W1700K_NAND') or \
    (BUILT_PART.read_text().strip() if BUILT_PART.is_file() else '') or 'w25n04kv'
PART = PARTS.get(_name)
if PART is None:
    sys.exit(f'partitions: unknown NAND part {_name!r}; W1700K_NAND must be one of '
             f'{", ".join(PARTS)}')
PAGE_BYTES = PART.page
BLOCK_BYTES = PART.page * PART.block_pages
TOTAL_BLOCKS = CHIP_BYTES // BLOCK_BYTES
LEB_BYTES = BLOCK_BYTES - 2 * PAGE_BYTES    # UBI LEB: a block less two header pages

# (offset, length), ascending and contiguous over the whole chip.
GEOMETRY = {
    'bootloader': (0x00000000, 0x00200000),   # vendor: BL2/BL31 and stock U-Boot
    'uenv': (0x00200000, 0x00200000),         # vendor: stock U-Boot environment
    'calibration': (0x00400000, 0x00200000),  # vendor: identity and radio calibration
    'loader': (0x00600000, 0x00200000),       # ours: our U-Boot FIT, read by stock
    'system': (0x00800000, 0x03000000),       # ours: UBI with environment, FIT, root
    'durable': (0x03800000, 0x02000000),      # ours: UBI with the durable UBIFS
    'scratch': (0x05800000, 0x16600000),      # ours: unused, never erased
    'reserved-bmt': (0x1be00000, 0x04200000), # vendor: BMT reserve pool
}

# Read-only partitions per stage. The loader can rewrite everything we own; Linux
# keeps `system` and `scratch` read-only and opens `durable` only on request.
READ_ONLY = {
    'loader': {'bootloader', 'uenv', 'calibration', 'loader', 'reserved-bmt'},
    'linux': {'bootloader', 'uenv', 'calibration', 'loader', 'system', 'scratch',
              'reserved-bmt'},
}
DEVICE_TREES = {
    'platform/linux/dts/an7581-w1700k-sdr.dts': 'linux',
    'platform/loader/an7581-w1700k-sdr-loader.dts': 'loader',
}
BEGIN = '\t\t// >>> generated by platform/partitions.py; edit that, not this'
END = '\t\t// <<< end generated partition table'

# Physical block in the vendor reserve that holds the BMT transaction journal.
# The engine checks at attach time that it is erased or holds its own journal.
JOURNAL_PHYSICAL_BLOCK = PART.journal

# UBI. Both U-Boot and Linux reserve 20 PEBs per 1024 of the whole chip for bad
# blocks, and four more for the layout volume, wear levelling and atomic LEB change.
UBI_BAD_RESERVE_PEBS = CHIP_BYTES // BLOCK_BYTES * 20 // 1024
UBI_INTERNAL_PEBS = 4
ENV_BYTES = 0x4000
FIT_VOLUME_LEBS = 0xf80000 // LEB_BYTES     # 15.5 MiB on either part


def ubi_lebs(partition):
    return GEOMETRY[partition][1] // BLOCK_BYTES - UBI_BAD_RESERVE_PEBS - UBI_INTERNAL_PEBS


# `system` volumes in id order: (name, type, LEBs). The root takes what is left.
SYSTEM_VOLUMES = (
    ('ubootenv', 'dynamic', 1),
    ('ubootenv2', 'dynamic', 1),
    ('fit', 'static', FIT_VOLUME_LEBS),
    ('rootfs', 'static', ubi_lebs('system') - 2 - FIT_VOLUME_LEBS),
)
DURABLE_LEBS = ubi_lebs('durable')
FIT_VOLUME_BYTES = FIT_VOLUME_LEBS * LEB_BYTES
ROOTFS_VOLUME_BYTES = SYSTEM_VOLUMES[3][2] * LEB_BYTES


def check_table():
    """Contiguous, ascending, block-aligned, covering exactly the whole chip."""
    cursor = 0
    for name, (offset, length) in GEOMETRY.items():
        if offset != cursor:
            raise ValueError(f'{name} leaves a gap or overlaps at {offset:#x}')
        if not length or length % BLOCK_BYTES or offset % BLOCK_BYTES:
            raise ValueError(f'{name} is not block-aligned')
        cursor = offset + length
    if cursor != CHIP_BYTES:
        raise ValueError(f'the table covers {cursor:#x}, not {CHIP_BYTES:#x}')
    for stage, names in READ_ONLY.items():
        if not names <= set(GEOMETRY):
            raise ValueError(f'{stage} names an unknown partition')
    if sum(lebs for _, _, lebs in SYSTEM_VOLUMES) > ubi_lebs('system'):
        raise ValueError('the system volumes do not fit the partition')
    reserve_first = TOTAL_BLOCKS - min(TOTAL_BLOCKS * 8 // 100, 250)
    if not reserve_first < JOURNAL_PHYSICAL_BLOCK < TOTAL_BLOCKS:
        raise ValueError('the BMT journal is outside the reserve')
    # Every factory-bad block shifts the logical area up by one; both parts allow
    # up to 40 of them.
    if sum(GEOMETRY['scratch']) // BLOCK_BYTES > reserve_first - 40:
        raise ValueError('scratch reaches into the blocks a factory BBT can shift into')


def policy_header():
    """airoha_bmt_policy.h: the part's geometry and the logical blocks the BMT
    engine may write."""
    check_table()
    first = GEOMETRY['system'][0] // BLOCK_BYTES
    end = sum(GEOMETRY['scratch']) // BLOCK_BYTES
    return ('/* Generated by platform/partitions.py; do not edit. */\n'
            '#ifndef AIROHA_BMT_POLICY_H\n#define AIROHA_BMT_POLICY_H\n'
            f'#define BMT_PART "{PART.name}"\n'
            f'#define BMT_PAGE_BYTES {PAGE_BYTES}u\n'
            f'#define BMT_OOB_BYTES {PART.oob}u\n'
            f'#define BMT_OOB_FREE {PART.oob_free}u\n'
            f'#define BMT_BLOCK_PAGES {PART.block_pages}u\n'
            f'#define BMT_TOTAL_BLOCKS {TOTAL_BLOCKS}u\n'
            f'#define BMT_WRITE_FIRST {first}u\n'
            f'#define BMT_WRITE_END {end}u\n'
            f'#define BMT_FAST_FIRST {first}u\n'
            f'#define BMT_FAST_END {end}u\n'
            f'#define BMT_JOURNAL_BLOCK {JOURNAL_PHYSICAL_BLOCK}u\n'
            '#endif\n')


def fragment(stage):
    """The device-tree partition nodes for one stage."""
    check_table()
    lines = [BEGIN, '\t\t// Vendor-logical offsets; BBT shift + BMT substitution exactly once.']
    for name, (offset, length) in GEOMETRY.items():
        lines += [f'\t\t{name}@{offset:x} {{', f'\t\t\tlabel = "{name}";',
                  f'\t\t\treg = <{offset:#010x} {length:#010x}>;']
        if name in READ_ONLY[stage]:
            lines.append('\t\t\tread-only;')
        lines += ['\t\t};', '']
    lines[-1] = END
    return '\n'.join(lines) + '\n'


def _region(text, path):
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise ValueError(f'{path}: expected one generated partition region')
    start = text.index(BEGIN)
    return start, text.index(END, start) + len(END) + 1


def check(path, stage):
    text = (ROOT / path).read_text()
    start, end = _region(text, path)
    if text[start:end] != fragment(stage):
        raise ValueError(f'{path} has a stale partition table; '
                         'run platform/partitions.py --write')


def write(path, stage):
    target = ROOT / path
    text = target.read_text()
    start, end = _region(text, path)
    updated = text[:start] + fragment(stage) + text[end:]
    if updated != text:
        target.write_text(updated)
        return True
    return False


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--write', action='store_true',
                        help='regenerate the device-tree partition regions')
    args = parser.parse_args(argv)
    try:
        for path, stage in DEVICE_TREES.items():
            if args.write:
                if write(path, stage):
                    print(f'partitions: rewrote {path}')
            else:
                check(path, stage)
    except ValueError as error:
        sys.exit(f'partitions: {error}')
    print(f'partitions: {len(GEOMETRY)} partitions; device trees current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
